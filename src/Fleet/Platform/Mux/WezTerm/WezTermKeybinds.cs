using System.Text;
using Fleet.Platform.Mux.WezTerm.Models;
using Fleet.Shared.Constants;
using Fleet.Shared.Keymap;
using Fleet.Ui.Constants;
using Fleet.Shared.Keymap.Enums;
using Fleet.Ui;

namespace Fleet.Platform.Mux.WezTerm;

public static class WezTermKeybinds
{

    public static string Generate(
        Keymap keymap,
        string fleetExecutable,
        string workspaceRequest,
        string notifyRequest = "")
    {
        var chord = WezTermChord.From(keymap.PrefixText);
        var head = WezTermChord.From(keymap.TextFor(FleetAction.OpenHead));
        var headVoice = WezTermChord.From(keymap.TextFor(FleetAction.OpenHeadVoice));
        var exe = fleetExecutable.Replace("\\", "\\\\", StringComparison.Ordinal);
        var request = workspaceRequest.Replace("\\", "\\\\", StringComparison.Ordinal);
        var notify = notifyRequest.Replace("\\", "\\\\", StringComparison.Ordinal);

        var sb = new StringBuilder();

        sb.AppendLine("-- generated by: fleet apply-keybinds");
        sb.AppendLine("-- edit fleet's keybinds instead of this file; it is overwritten.");
        sb.AppendLine("--");
        sb.AppendLine("-- add to .wezterm.lua:");
        sb.AppendLine("--   local fleet = require 'fleet'");
        sb.AppendLine("--   fleet.apply(config)");
        sb.AppendLine();
        sb.AppendLine("local wezterm = require 'wezterm'");
        sb.AppendLine("local act = wezterm.action");
        sb.AppendLine();
        sb.AppendLine("local M = {}");
        sb.AppendLine();
        sb.AppendLine($"M.fleet = '{exe}'");
        sb.AppendLine();
        sb.AppendLine("-- The menu belongs to windows fleet is actually running in. A fleet dashboard");
        sb.AppendLine("-- marks its pane with a WezTerm user var holding the project name; without one");
        sb.AppendLine("-- the chord is forwarded to the pane untouched, so unrelated windows keep the");
        sb.AppendLine("-- key.");
        sb.AppendLine("local function fleet_project(window, quiet)");
        sb.AppendLine("  local ok, tabs = pcall(function()");
        sb.AppendLine("    return window:mux_window():tabs()");
        sb.AppendLine("  end)");
        sb.AppendLine();
        sb.AppendLine("  if not ok or not tabs then");
        sb.AppendLine("    return nil");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  for _, tab in ipairs(tabs) do");
        sb.AppendLine("    for _, p in ipairs(tab:panes()) do");
        sb.AppendLine("      local vars = p:get_user_vars()");
        sb.AppendLine($"      local project = vars and vars['{WezTermUserVars.FleetVar}']");
        sb.AppendLine("      if project and project ~= '' then");
        sb.AppendLine("        if not quiet then");
        sb.AppendLine("          wezterm.log_info('fleet: dashboard pane found for ' .. project)");
        sb.AppendLine("        end");
        sb.AppendLine("        return project, p");
        sb.AppendLine("      end");
        sb.AppendLine("    end");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  if not quiet then");
        sb.AppendLine("    wezterm.log_info('fleet: no dashboard pane in this window, forwarding the key')");
        sb.AppendLine("  end");
        sb.AppendLine("  return nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- The CLI cannot switch workspaces: activate-pane reports success but leaves");
        sb.AppendLine("-- the client where it was. Hidden agents live in their own workspace, so fleet");
        sb.AppendLine("-- asks for a switch by writing a file and this handler performs it. update-status");
        sb.AppendLine("-- fires about once a second, which is the only timer wezterm offers.");
        sb.AppendLine($"M.workspace_request = '{request}'");
        sb.AppendLine();
        sb.AppendLine("-- The left segment is wezterm's workspace name by default, which says");
        sb.AppendLine("-- nothing useful. A window running a fleet dashboard shows its project.");
        sb.AppendLine("-- The left status belongs to whoever configured the tab bar. fleet only");
        sb.AppendLine("-- exposes the lookup, because two update-status handlers writing the same");
        sb.AppendLine("-- slot either fight once a second or silently overwrite each other:");
        sb.AppendLine("--");
        sb.AppendLine("--   local ok, fleet = pcall(require, 'fleet')");
        sb.AppendLine("--   local name = (ok and fleet.project(win)) or win:active_workspace()");
        sb.AppendLine("--   win:set_left_status(wezterm.format(pill(' ' .. name .. ' ')))");
        sb.AppendLine($"M.ship = '{FleetGlyphs.Ship}'");
        sb.AppendLine();
        sb.AppendLine("function M.project(window)");
        sb.AppendLine("  local found, project = pcall(fleet_project, window, true)");
        sb.AppendLine();
        sb.AppendLine("  return (found and project) or nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("function M.label(window)");
        sb.AppendLine("  local project = M.project(window)");
        sb.AppendLine();
        sb.AppendLine("  return project and (M.ship .. '  ' .. project) or nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Signals pushed by the dashboard as user vars. They cross mux and ssh");
        sb.AppendLine("-- domains, unlike the request files, which stay as a local fallback.");
        sb.AppendLine("wezterm.on('user-var-changed', function(window, pane, name, value)");
        sb.AppendLine("  local body = value:gsub('^[^\\n]*\\n?', '')");
        sb.AppendLine();
        sb.AppendLine("  if name == 'fleet-notify' then");
        sb.AppendLine("    for line in body:gmatch('[^\\r\\n]+') do");
        sb.AppendLine("      window:toast_notification('fleet', line, nil, 4000)");
        sb.AppendLine("    end");
        sb.AppendLine("  elseif name == 'fleet-workspace' then");
        sb.AppendLine("    local wanted = body:gsub('%s+$', '')");
        sb.AppendLine();
        sb.AppendLine("    if wanted ~= '' and window:active_workspace() ~= wanted then");
        sb.AppendLine("      wezterm.log_info('fleet: switching to workspace ' .. wanted)");
        sb.AppendLine("      window:perform_action(act.SwitchToWorkspace { name = wanted }, pane)");
        sb.AppendLine("    end");
        sb.AppendLine("  end");
        sb.AppendLine("end)");
        sb.AppendLine();
        sb.AppendLine("-- Kept for configs that call it; tab markers are retired.");
        sb.AppendLine("function M.tab_marker(_tab)");
        sb.AppendLine("  return nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Notifications ride the same file mechanism: fleet appends lines and the");
        sb.AppendLine("-- next update-status tick shows each as a toast.");
        sb.AppendLine($"M.notify_request = '{notify}'");
        sb.AppendLine();
        sb.AppendLine("local function drain_notifications(window)");
        sb.AppendLine("  if M.notify_request == '' then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local handle = io.open(M.notify_request, 'r')");
        sb.AppendLine();
        sb.AppendLine("  if not handle then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local text = handle:read('*a')");
        sb.AppendLine("  handle:close()");
        sb.AppendLine("  os.remove(M.notify_request)");
        sb.AppendLine();
        sb.AppendLine("  for line in (text or ''):gmatch('[^\\r\\n]+') do");
        sb.AppendLine("    window:toast_notification('fleet', line, nil, 4000)");
        sb.AppendLine("  end");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("wezterm.on('update-status', function(window, _pane)");
        sb.AppendLine("  pcall(drain_notifications, window)");
        sb.AppendLine();
        sb.AppendLine("  local handle = io.open(M.workspace_request, 'r')");
        sb.AppendLine();
        sb.AppendLine("  if not handle then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local wanted = handle:read('*a')");
        sb.AppendLine("  handle:close()");
        sb.AppendLine("  os.remove(M.workspace_request)");
        sb.AppendLine();
        sb.AppendLine("  wanted = wanted and wanted:gsub('%s+$', '')");
        sb.AppendLine();
        sb.AppendLine("  if not wanted or wanted == '' then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  if window:active_workspace() == wanted then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  wezterm.log_info('fleet: switching to workspace ' .. wanted)");
        sb.AppendLine("  window:perform_action(act.SwitchToWorkspace { name = wanted }, _pane)");
        sb.AppendLine("end)");
        sb.AppendLine();
        sb.AppendLine("-- The head orchestrator: one Claude above every project. wezterm has no");
        sb.AppendLine("-- floating panes, so the head lives in a workspace of its own and the chord");
        sb.AppendLine("-- switches the window into it and back. Hiding never stops it, so the session");
        sb.AppendLine("-- survives across projects and windows. Each chord shows the head in its own");
        sb.AppendLine("-- mode: the chord of the running mode hides it again, the other chord restarts");
        sb.AppendLine("-- it in the new mode with --continue, so the conversation carries over.");
        sb.AppendLine("-- Claude's /voice saves to the user's own settings, which the head's");
        sb.AppendLine("-- --settings file outranks, so the mode cannot change inside the session.");
        sb.AppendLine($"M.head_workspace = '{FleetWorkspaces.Head}'");
        sb.AppendLine();
        sb.AppendLine("local function head_args(voice)");
        sb.AppendLine("  local args = { M.fleet, 'head' }");
        sb.AppendLine();
        sb.AppendLine("  if voice then");
        sb.AppendLine("    table.insert(args, '--voice')");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  return args");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("local function head_panes()");
        sb.AppendLine("  local found = {}");
        sb.AppendLine();
        sb.AppendLine("  for _, w in ipairs(wezterm.mux.all_windows()) do");
        sb.AppendLine("    if w:get_workspace() == M.head_workspace then");
        sb.AppendLine("      for _, tab in ipairs(w:tabs()) do");
        sb.AppendLine("        for _, p in ipairs(tab:panes()) do");
        sb.AppendLine("          table.insert(found, p)");
        sb.AppendLine("        end");
        sb.AppendLine("      end");
        sb.AppendLine("    end");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  return found");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- The new head splits off the old one so the workspace never empties, then");
        sb.AppendLine("-- the old panes are killed. In the background: a blocking wezterm cli call");
        sb.AppendLine("-- would wait on the very GUI that is running this callback.");
        sb.AppendLine("local function restart_head(voice)");
        sb.AppendLine("  local old = head_panes()");
        sb.AppendLine();
        sb.AppendLine("  if #old == 0 then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  wezterm.log_info('fleet: restarting the head, voice ' .. tostring(voice))");
        sb.AppendLine("  old[1]:split { args = head_args(voice) }");
        sb.AppendLine();
        sb.AppendLine("  for _, p in ipairs(old) do");
        sb.AppendLine("    wezterm.background_child_process {");
        sb.AppendLine("      'wezterm', 'cli', 'kill-pane', '--pane-id', tostring(p:pane_id()),");
        sb.AppendLine("    }");
        sb.AppendLine("  end");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("local function toggle_head(window, pane, voice, key, mods)");
        sb.AppendLine("  local here = window:active_workspace()");
        sb.AppendLine("  local running = wezterm.GLOBAL.fleet_head_voice == true");
        sb.AppendLine();
        sb.AppendLine("  if here == M.head_workspace then");
        sb.AppendLine("    if voice ~= running then");
        sb.AppendLine("      restart_head(voice)");
        sb.AppendLine("      wezterm.GLOBAL.fleet_head_voice = voice");
        sb.AppendLine("      return");
        sb.AppendLine("    end");
        sb.AppendLine();
        sb.AppendLine("    local back = wezterm.GLOBAL.fleet_head_return or 'default'");
        sb.AppendLine("    window:perform_action(act.SwitchToWorkspace { name = back }, pane)");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  if not fleet_project(window, true) then");
        sb.AppendLine("    window:perform_action(act.SendKey { key = key, mods = mods }, pane)");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  wezterm.GLOBAL.fleet_head_return = here");
        sb.AppendLine();
        sb.AppendLine("  if voice ~= running then");
        sb.AppendLine("    restart_head(voice)");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  wezterm.GLOBAL.fleet_head_voice = voice");
        sb.AppendLine();
        sb.AppendLine("  window:perform_action(");
        sb.AppendLine("    act.SwitchToWorkspace { name = M.head_workspace, spawn = { args = head_args(voice) } },");
        sb.AppendLine("    pane");
        sb.AppendLine("  )");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("function M.apply(config)");
        sb.AppendLine("  config.keys = config.keys or {}");
        sb.AppendLine();
        sb.AppendLine("  table.insert(config.keys, {");
        sb.AppendLine($"    key = '{chord.Key}',");
        sb.AppendLine($"    mods = '{chord.Mods}',");
        sb.AppendLine("    action = wezterm.action_callback(function(window, pane)");
        sb.AppendLine("      local project = fleet_project(window)");
        sb.AppendLine();
        sb.AppendLine("      if not project then");
        sb.AppendLine("        window:perform_action(");
        sb.AppendLine($"          act.SendKey {{ key = '{chord.Key}', mods = '{chord.Mods}' }},");
        sb.AppendLine("          pane");
        sb.AppendLine("        )");
        sb.AppendLine("        return");
        sb.AppendLine("      end");
        sb.AppendLine();
        sb.AppendLine("      -- fleet renders its own menu, styled like the rest of it. A tab");
        sb.AppendLine("      -- rather than a split, so no pane is resized; it closes itself.");
        sb.AppendLine("      -- Over a mux/ssh domain the baked path is a different machine's,");
        sb.AppendLine("      -- so spawn plain 'fleet' from the remote PATH instead.");
        sb.AppendLine("      local exe = M.fleet");
        sb.AppendLine();
        sb.AppendLine("      local ok_domain, domain = pcall(function()");
        sb.AppendLine("        return pane:get_domain_name()");
        sb.AppendLine("      end)");
        sb.AppendLine();
        sb.AppendLine("      if ok_domain and domain and domain ~= 'local' then");
        sb.AppendLine("        exe = 'fleet'");
        sb.AppendLine("      end");
        sb.AppendLine();
        sb.AppendLine("      window:perform_action(");
        sb.AppendLine("        act.SpawnCommandInNewTab {");
        sb.AppendLine("          domain = 'CurrentPaneDomain',");
        sb.AppendLine("          args = { exe, 'menu', '--project', project },");
        sb.AppendLine("        },");
        sb.AppendLine("        pane");
        sb.AppendLine("      )");
        sb.AppendLine("    end),");
        sb.AppendLine("  })");
        sb.AppendLine();
        AppendHeadKey(sb, head, voice: false);
        AppendHeadKey(sb, headVoice, voice: true);
        sb.AppendLine("  -- Guard the dashboard pane from the leader close binding (e.g. LEADER x):");
        sb.AppendLine("  -- closing it would tear down the project view, so refuse it there and");
        sb.AppendLine("  -- close any other pane as usual. Applied after your own keys, so keep");
        sb.AppendLine("  -- fleet.apply(config) last if you bind LEADER x yourself.");
        sb.AppendLine("  table.insert(config.keys, {");
        sb.AppendLine("    key = 'x',");
        sb.AppendLine("    mods = 'LEADER',");
        sb.AppendLine("    action = wezterm.action_callback(function(window, pane)");
        sb.AppendLine("      local vars = pane:get_user_vars()");
        sb.AppendLine($"      local project = vars and vars['{WezTermUserVars.FleetVar}']");
        sb.AppendLine("      if project and project ~= '' then");
        sb.AppendLine("        wezterm.log_info('fleet: refusing to close the dashboard pane')");
        sb.AppendLine("        return");
        sb.AppendLine("      end");
        sb.AppendLine("      window:perform_action(act.CloseCurrentPane { confirm = true }, pane)");
        sb.AppendLine("    end),");
        sb.AppendLine("  })");
        sb.AppendLine();
        sb.AppendLine("  return config");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Compatibility with the predecessor's call shape. A .wezterm.lua written for");
        sb.AppendLine("-- the old Go fleet calls fleet.setup(config, opts); its pcall guards only the");
        sb.AppendLine("-- require, so a module without setup would fail the whole config at load.");
        sb.AppendLine("function M.setup(config, _opts)");
        sb.AppendLine("  return M.apply(config)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("return M");

        return sb.ToString();
    }

    private static void AppendHeadKey(StringBuilder sb, WezTermChord chord, bool voice)
    {
        var flag = voice ? "true" : "false";

        sb.AppendLine("  table.insert(config.keys, {");
        sb.AppendLine($"    key = '{chord.Key}',");
        sb.AppendLine($"    mods = '{chord.Mods}',");
        sb.AppendLine("    action = wezterm.action_callback(function(window, pane)");
        sb.AppendLine($"      toggle_head(window, pane, {flag}, '{chord.Key}', '{chord.Mods}')");
        sb.AppendLine("    end),");
        sb.AppendLine("  })");
        sb.AppendLine();
    }
}
