using System.Text;
using Fleet.Platform.Mux.WezTerm.Models;
using Fleet.Shared.Keymap;
using Fleet.Ui.Constants;
using Fleet.Shared.Keymap.Enums;
using Fleet.Ui;

namespace Fleet.Platform.Mux.WezTerm;

public static class WezTermKeybinds
{

    public static string Generate(
        Keymap keymap,
        string fleetExecutable,
        string workspaceRequest,
        string notifyRequest = "",
        string tabStateGlob = "")
    {
        var chord = WezTermChord.From(keymap.PrefixText);
        var exe = fleetExecutable.Replace("\\", "\\\\", StringComparison.Ordinal);
        var request = workspaceRequest.Replace("\\", "\\\\", StringComparison.Ordinal);
        var notify = notifyRequest.Replace("\\", "\\\\", StringComparison.Ordinal);
        var tabState = tabStateGlob.Replace('\\', '/');

        var sb = new StringBuilder();

        sb.AppendLine("-- generated by: fleet apply-keybinds");
        sb.AppendLine("-- edit fleet's keybinds instead of this file; it is overwritten.");
        sb.AppendLine("--");
        sb.AppendLine("-- add to .wezterm.lua:");
        sb.AppendLine("--   local fleet = require 'fleet'");
        sb.AppendLine("--   fleet.apply(config)");
        sb.AppendLine();
        sb.AppendLine("local wezterm = require 'wezterm'");
        sb.AppendLine("local act = wezterm.action");
        sb.AppendLine();
        sb.AppendLine("local M = {}");
        sb.AppendLine();
        sb.AppendLine($"M.fleet = '{exe}'");
        sb.AppendLine();
        sb.AppendLine("-- The menu belongs to windows fleet is actually running in. A fleet dashboard");
        sb.AppendLine("-- marks its pane with a WezTerm user var holding the project name; without one");
        sb.AppendLine("-- the chord is forwarded to the pane untouched, so unrelated windows keep the");
        sb.AppendLine("-- key.");
        sb.AppendLine("local function fleet_project(window, quiet)");
        sb.AppendLine("  local ok, tabs = pcall(function()");
        sb.AppendLine("    return window:mux_window():tabs()");
        sb.AppendLine("  end)");
        sb.AppendLine();
        sb.AppendLine("  if not ok or not tabs then");
        sb.AppendLine("    return nil");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  for _, tab in ipairs(tabs) do");
        sb.AppendLine("    for _, p in ipairs(tab:panes()) do");
        sb.AppendLine("      local vars = p:get_user_vars()");
        sb.AppendLine($"      local project = vars and vars['{WezTermUserVars.FleetVar}']");
        sb.AppendLine("      if project and project ~= '' then");
        sb.AppendLine("        if not quiet then");
        sb.AppendLine("          wezterm.log_info('fleet: dashboard pane found for ' .. project)");
        sb.AppendLine("        end");
        sb.AppendLine("        return project, p");
        sb.AppendLine("      end");
        sb.AppendLine("    end");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  if not quiet then");
        sb.AppendLine("    wezterm.log_info('fleet: no dashboard pane in this window, forwarding the key')");
        sb.AppendLine("  end");
        sb.AppendLine("  return nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- The CLI cannot switch workspaces: activate-pane reports success but leaves");
        sb.AppendLine("-- the client where it was. Hidden agents live in their own workspace, so fleet");
        sb.AppendLine("-- asks for a switch by writing a file and this handler performs it. update-status");
        sb.AppendLine("-- fires about once a second, which is the only timer wezterm offers.");
        sb.AppendLine($"M.workspace_request = '{request}'");
        sb.AppendLine();
        sb.AppendLine("-- The left segment is wezterm's workspace name by default, which says");
        sb.AppendLine("-- nothing useful. A window running a fleet dashboard shows its project.");
        sb.AppendLine("-- The left status belongs to whoever configured the tab bar. fleet only");
        sb.AppendLine("-- exposes the lookup, because two update-status handlers writing the same");
        sb.AppendLine("-- slot either fight once a second or silently overwrite each other:");
        sb.AppendLine("--");
        sb.AppendLine("--   local ok, fleet = pcall(require, 'fleet')");
        sb.AppendLine("--   local name = (ok and fleet.project(win)) or win:active_workspace()");
        sb.AppendLine("--   win:set_left_status(wezterm.format(pill(' ' .. name .. ' ')))");
        sb.AppendLine($"M.ship = '{FleetGlyphs.Ship}'");
        sb.AppendLine();
        sb.AppendLine("function M.project(window)");
        sb.AppendLine("  local found, project = pcall(fleet_project, window, true)");
        sb.AppendLine();
        sb.AppendLine("  return (found and project) or nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("function M.label(window)");
        sb.AppendLine("  local project = M.project(window)");
        sb.AppendLine();
        sb.AppendLine("  return project and (M.ship .. '  ' .. project) or nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Agent activity for a tab, published by the dashboard as tabstate files");
        sb.AppendLine("-- of '<tab title>\\t<status>' lines. Cached; the bar redraws every second.");
        sb.AppendLine($"M.tabstate_glob = '{tabState}'");
        sb.AppendLine();
        sb.AppendLine("local state_cache = { at = 0, map = {} }");
        sb.AppendLine();
        sb.AppendLine("local function tab_states()");
        sb.AppendLine("  if M.tabstate_glob == '' then");
        sb.AppendLine("    return state_cache.map");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local now = os.time()");
        sb.AppendLine("  if now - state_cache.at < 2 then");
        sb.AppendLine("    return state_cache.map");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local map = {}");
        sb.AppendLine("  for _, file in ipairs(wezterm.glob(M.tabstate_glob)) do");
        sb.AppendLine("    local handle = io.open(file, 'r')");
        sb.AppendLine("    if handle then");
        sb.AppendLine("      for line in handle:lines() do");
        sb.AppendLine("        local title, status = line:match('^(.-)\\t(%a+)%s*$')");
        sb.AppendLine("        if title and status then");
        sb.AppendLine("          map[title] = status");
        sb.AppendLine("        end");
        sb.AppendLine("      end");
        sb.AppendLine("      handle:close()");
        sb.AppendLine("    end");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  state_cache = { at = now, map = map }");
        sb.AppendLine("  return map");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("local state_colors = {");
        sb.AppendLine("  working = '#f9e2af',");
        sb.AppendLine("  waiting = '#f38ba8',");
        sb.AppendLine("  failed = '#f38ba8',");
        sb.AppendLine("  idle = '#a6e3a1',");
        sb.AppendLine("  done = '#a6e3a1',");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("function M.tab_marker(tab)");
        sb.AppendLine("  local title = tab.tab_title");
        sb.AppendLine("  if not title or #title == 0 then");
        sb.AppendLine("    return nil");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local color = state_colors[tab_states()[title] or '']");
        sb.AppendLine();
        sb.AppendLine("  return color and { glyph = utf8.char(0x25cf), color = color } or nil");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Notifications ride the same file mechanism: fleet appends lines and the");
        sb.AppendLine("-- next update-status tick shows each as a toast.");
        sb.AppendLine($"M.notify_request = '{notify}'");
        sb.AppendLine();
        sb.AppendLine("local function drain_notifications(window)");
        sb.AppendLine("  if M.notify_request == '' then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local handle = io.open(M.notify_request, 'r')");
        sb.AppendLine();
        sb.AppendLine("  if not handle then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local text = handle:read('*a')");
        sb.AppendLine("  handle:close()");
        sb.AppendLine("  os.remove(M.notify_request)");
        sb.AppendLine();
        sb.AppendLine("  for line in (text or ''):gmatch('[^\\r\\n]+') do");
        sb.AppendLine("    window:toast_notification('fleet', line, nil, 4000)");
        sb.AppendLine("  end");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("wezterm.on('update-status', function(window, _pane)");
        sb.AppendLine("  pcall(drain_notifications, window)");
        sb.AppendLine();
        sb.AppendLine("  local handle = io.open(M.workspace_request, 'r')");
        sb.AppendLine();
        sb.AppendLine("  if not handle then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  local wanted = handle:read('*a')");
        sb.AppendLine("  handle:close()");
        sb.AppendLine("  os.remove(M.workspace_request)");
        sb.AppendLine();
        sb.AppendLine("  wanted = wanted and wanted:gsub('%s+$', '')");
        sb.AppendLine();
        sb.AppendLine("  if not wanted or wanted == '' then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  if window:active_workspace() == wanted then");
        sb.AppendLine("    return");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  wezterm.log_info('fleet: switching to workspace ' .. wanted)");
        sb.AppendLine("  window:perform_action(act.SwitchToWorkspace { name = wanted }, _pane)");
        sb.AppendLine("end)");
        sb.AppendLine();
        sb.AppendLine("function M.apply(config)");
        sb.AppendLine("  config.keys = config.keys or {}");
        sb.AppendLine();
        sb.AppendLine("  table.insert(config.keys, {");
        sb.AppendLine($"    key = '{chord.Key}',");
        sb.AppendLine($"    mods = '{chord.Mods}',");
        sb.AppendLine("    action = wezterm.action_callback(function(window, pane)");
        sb.AppendLine("      local project = fleet_project(window)");
        sb.AppendLine();
        sb.AppendLine("      if not project then");
        sb.AppendLine("        window:perform_action(");
        sb.AppendLine($"          act.SendKey {{ key = '{chord.Key}', mods = '{chord.Mods}' }},");
        sb.AppendLine("          pane");
        sb.AppendLine("        )");
        sb.AppendLine("        return");
        sb.AppendLine("      end");
        sb.AppendLine();
        sb.AppendLine("      -- fleet renders its own menu, styled like the rest of it. A tab");
        sb.AppendLine("      -- rather than a split, so no pane is resized; it closes itself.");
        sb.AppendLine("      window:perform_action(");
        sb.AppendLine("        act.SpawnCommandInNewTab {");
        sb.AppendLine("          args = { M.fleet, 'menu', '--project', project },");
        sb.AppendLine("        },");
        sb.AppendLine("        pane");
        sb.AppendLine("      )");
        sb.AppendLine("    end),");
        sb.AppendLine("  })");
        sb.AppendLine();
        sb.AppendLine("  -- Guard the dashboard pane from the leader close binding (e.g. LEADER x):");
        sb.AppendLine("  -- closing it would tear down the project view, so refuse it there and");
        sb.AppendLine("  -- close any other pane as usual. Applied after your own keys, so keep");
        sb.AppendLine("  -- fleet.apply(config) last if you bind LEADER x yourself.");
        sb.AppendLine("  table.insert(config.keys, {");
        sb.AppendLine("    key = 'x',");
        sb.AppendLine("    mods = 'LEADER',");
        sb.AppendLine("    action = wezterm.action_callback(function(window, pane)");
        sb.AppendLine("      local vars = pane:get_user_vars()");
        sb.AppendLine($"      local project = vars and vars['{WezTermUserVars.FleetVar}']");
        sb.AppendLine("      if project and project ~= '' then");
        sb.AppendLine("        wezterm.log_info('fleet: refusing to close the dashboard pane')");
        sb.AppendLine("        return");
        sb.AppendLine("      end");
        sb.AppendLine("      window:perform_action(act.CloseCurrentPane { confirm = true }, pane)");
        sb.AppendLine("    end),");
        sb.AppendLine("  })");
        sb.AppendLine();
        sb.AppendLine("  return config");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Compatibility with the predecessor's call shape. A .wezterm.lua written for");
        sb.AppendLine("-- the old Go fleet calls fleet.setup(config, opts); its pcall guards only the");
        sb.AppendLine("-- require, so a module without setup would fail the whole config at load.");
        sb.AppendLine("function M.setup(config, _opts)");
        sb.AppendLine("  return M.apply(config)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("return M");

        return sb.ToString();
    }
}
